function initLiveDotsBackground() {
  const dotsCanvas = document.getElementById('live-dots-canvas');
  if (!dotsCanvas) return;

  const dotsCtx = dotsCanvas.getContext('2d');
  if (!dotsCtx) return;

  let width = 0;
  let height = 0;
  let dpr = window.devicePixelRatio || 1;
  const spacing = 34; // шаг между точками в px
  let animId = null;
  let isTabVisible = true;
  const ripples = [];

  function resize() {
    dpr = window.devicePixelRatio || 1;
    width = window.innerWidth;
    height = window.innerHeight;

    // Ресайз фонового канваса с точками
    dotsCanvas.width = Math.floor(width * dpr);
    dotsCanvas.height = Math.floor(height * dpr);
    dotsCanvas.style.width = width + 'px';
    dotsCanvas.style.height = height + 'px';
    dotsCtx.setTransform(1, 0, 0, 1, 0, 0);
    dotsCtx.scale(dpr, dpr);
  }

  window.addEventListener('resize', resize, { passive: true });
  resize();

  // Обработчик нажатия (по кнопкам, карточкам или фону)
  let lastTriggerTime = 0;
  let lastTriggerX = 0;
  let lastTriggerY = 0;

  function triggerWave(clientX, clientY) {
    if (clientX == null || clientY == null) return;
    const now = performance.now();
    // Дедупликация одновременных pointerdown и click/touch
    if (now - lastTriggerTime < 70 && Math.hypot(clientX - lastTriggerX, clientY - lastTriggerY) < 15) {
      return;
    }
    lastTriggerTime = now;
    lastTriggerX = clientX;
    lastTriggerY = clientY;

    ripples.push({
      x: clientX,
      y: clientY,
      radius: 4,
      maxRadius: Math.max(width, height) * 0.9,
      speed: 6.2, // плавная плавная скорость расширения волны
      alpha: 0.70 // мягкая начальная интенсивность
    });

    if (!animId) {
      animId = requestAnimationFrame(render);
    }
  }

  // Перехватываем клики и тапы на самом верхнем уровне (capture: true)
  window.addEventListener('pointerdown', (e) => {
    triggerWave(e.clientX, e.clientY);
  }, { capture: true, passive: true });

  window.addEventListener('touchstart', (e) => {
    if (e.touches && e.touches[0]) {
      triggerWave(e.touches[0].clientX, e.touches[0].clientY);
    }
  }, { capture: true, passive: true });

  document.addEventListener('visibilitychange', () => {
    isTabVisible = !document.hidden;
    if (isTabVisible && !animId) {
      animId = requestAnimationFrame(render);
    }
  });

  const startTime = performance.now();

  function render(now) {
    if (!isTabVisible) {
      animId = null;
      return;
    }

    const curTime = now || performance.now();
    const time = (curTime - startTime) * 0.001;
    const isDark = document.body && document.body.classList.contains('midis-dark');

    // 1. Обновление активных импульсов волн (плавное затухание)
    for (let i = ripples.length - 1; i >= 0; i--) {
      const rip = ripples[i];
      rip.radius += rip.speed;
      rip.alpha *= 0.978; // шелковистое, очень плавное затухание
      if (rip.alpha < 0.008 || rip.radius >= rip.maxRadius) {
        ripples.splice(i, 1);
      }
    }

    // 2. Отрисовка сетки точек на фоновом канвасе (БЕЗ круговых линий и обводок)
    dotsCtx.clearRect(0, 0, width, height);

    const cols = Math.ceil(width / spacing) + 1;
    const rows = Math.ceil(height / spacing) + 1;
    const startX = (width % spacing) / 2;
    const startY = (height % spacing) / 2;

    // Слегка убавленная яркость точек — аккуратно, премиально, не слепит
    const baseAlpha = isDark ? 0.13 : 0.11;
    const dotR = isDark ? 255 : 70;
    const dotG = isDark ? 255 : 85;
    const dotB = isDark ? 255 : 108;

    for (let r = 0; r < rows; r++) {
      const baseY = startY + r * spacing;
      for (let c = 0; c < cols; c++) {
        const baseX = startX + c * spacing;

        // Спокойный органичный микро-ритм сетки
        const idleWave = Math.sin(time * 0.9 + c * 0.18 + r * 0.22);

        let waveGlow = 0;
        let pushX = 0;
        let pushY = 0;

        // Реакция точек на проходящую световую волну от нажатия (сверхплавная и деликатная)
        if (ripples.length > 0) {
          for (let i = 0; i < ripples.length; i++) {
            const rip = ripples[i];
            const dx = baseX - rip.x;
            const dy = baseY - rip.y;
            const dist = Math.sqrt(dx * dx + dy * dy);
            const distFromCrest = Math.abs(dist - rip.radius);
            const crestThickness = 95; // широкий и мягкий гребень для плавного перехода

            if (distFromCrest < crestThickness) {
              // Плавная косинусная кривая без резких скачков
              const normalizedDist = distFromCrest / crestThickness;
              const factor = Math.cos(normalizedDist * (Math.PI / 2)) * rip.alpha;
              if (factor > waveGlow) waveGlow = factor;
              if (dist > 1) {
                // Очень мягкий микро-импульс (1.5px) вместо резкого толчка
                const impulse = Math.sin((1 - normalizedDist) * Math.PI) * rip.alpha * 1.5;
                pushX += (dx / dist) * impulse;
                pushY += (dy / dist) * impulse;
              }
            }
          }
        }

        const curX = baseX + idleWave * 1.3 + pushX;
        const curY = baseY + Math.cos(time * 0.8 + c * 0.14 - r * 0.16) * 1.3 + pushY;

        let radius = 1.65;
        let fillStyle;

        if (waveGlow > 0.015) {
          // Мягкое благородное свечение оранжевым МИДиС без резких ослепляющих вспышек
          radius = 1.65 + waveGlow * 0.75;
          const orangeAlpha = Math.min(0.52, baseAlpha + waveGlow * 0.42);
          fillStyle = `rgba(252, 76, 2, ${orangeAlpha.toFixed(3)})`;
        } else {
          // Базовое спокойное микро-дыхание точек
          const alpha = baseAlpha + (idleWave + 1) * 0.022;
          fillStyle = `rgba(${dotR}, ${dotG}, ${dotB}, ${alpha.toFixed(3)})`;
        }

        dotsCtx.beginPath();
        dotsCtx.arc(curX, curY, radius, 0, Math.PI * 2);
        dotsCtx.fillStyle = fillStyle;
        dotsCtx.fill();
      }
    }

    animId = requestAnimationFrame(render);
  }

  animId = requestAnimationFrame(render);
}

