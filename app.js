let autoAdvanceTimer = null;

/**
 * Плавный автопереход на следующий шаг с визуальной подсветкой выбранной карточки
 * Даёт пользователю ~350мс увидеть свой выбор перед переходом
 */
function triggerAutoAdvance(targetStep, clickedElement) {
  if (autoAdvanceTimer) {
    clearTimeout(autoAdvanceTimer);
    autoAdvanceTimer = null;
  }

  // Очищаем подсветку со ВСЕХ карточек, чтобы устранить баг быстрого двойного клика
  document.querySelectorAll('.tile-selecting').forEach(el => el.classList.remove('tile-selecting'));

  if (clickedElement) {
    clickedElement.classList.add('tile-selecting');
  }

  autoAdvanceTimer = setTimeout(() => {
    document.querySelectorAll('.tile-selecting').forEach(el => el.classList.remove('tile-selecting'));
    goToStep(targetStep);
  }, 220);
}

function updateStep2SelectionBanner() {
  const banner = document.getElementById('current-spec-banner');
  if (!banner) return;
  const spec = state.specialization;
  if (!spec || !spec.name) {
    banner.style.display = 'none';
    return;
  }
  const courseText = state.course ? `${state.course} курс` : '1 курс';
  banner.innerHTML = `
    <span class="sel-check">✓</span>
    <span class="sel-text">Твой выбор: <strong>${spec.name}</strong> (${courseText})</span>
    <span class="sel-hint">Нажми на другую специальность, чтобы изменить</span>
  `;
  banner.style.display = 'flex';
}

function goToStep(targetStep, isInitial = false) {
  if (targetStep < 1 || targetStep > state.totalSteps) return;
  state.currentStep = targetStep;

  // Очищаем любые залипшие карточки с анимацией выбора
  document.querySelectorAll('.tile-selecting').forEach(el => el.classList.remove('tile-selecting'));

  // 1. Переключение видимости секций шагов
  document.querySelectorAll('.step-section').forEach((pane, idx) => {
    pane.classList.toggle('active', idx + 1 === targetStep);
  });

  // 2. Десктопная линия прогресса
  const progressPercent = Math.round(((targetStep - 1) / (state.totalSteps - 1)) * 100);
  const barFill = document.getElementById('stepper-bar-fill');
  if (barFill) {
    barFill.style.width = `${Math.max(10, progressPercent)}%`;
  }

  // 3. Десктопные кнопки шагов
  document.querySelectorAll('#stepper-buttons .step-btn').forEach(btn => {
    const s = parseInt(btn.dataset.step, 10);
    const isActive = s === targetStep;
    btn.classList.toggle('active', isActive);
    btn.classList.toggle('completed', s < targetStep);
    if (isActive) {
      btn.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
    }
  });

  // 4. Мобильный компактный степпер
  const mobileFill = document.getElementById('mobile-stepper-fill');
  if (mobileFill) {
    mobileFill.style.width = `${Math.max(12, progressPercent)}%`;
  }

  const stepTitles = {
    1: 'Шаг 1 из 5: Выбор задачи',
    2: 'Шаг 2 из 5: Специальность',
    3: 'Шаг 3 из 5: Стиль ответа',
    4: 'Шаг 4 из 5: Твой вопрос',
    5: 'Шаг 5 из 5: Готовый запрос'
  };
  const mobileTitle = document.getElementById('mobile-stepper-title');
  if (mobileTitle) {
    mobileTitle.textContent = stepTitles[targetStep] || `Шаг ${targetStep} из 5`;
  }

  const mobilePrevBtn = document.getElementById('mobile-stepper-btn-prev');
  if (mobilePrevBtn) {
    mobilePrevBtn.style.visibility = targetStep === 1 ? 'hidden' : 'visible';
  }

  // 5. Действия при входе на шаг
  if (targetStep === 2) {
    updateStep2SelectionBanner();
  } else if (targetStep === 4) {
    renderStep4Templates();
  } else if (targetStep === 5) {
    runPromptGeneration();
  }

  // 6. Плавный скролл к началу категории шагов (аккуратный скролл к степперу)
  if (!isInitial) {
    scrollToStepCategory();
  }
}

function scrollToStepCategory() {
  const isMobile = window.innerWidth <= 768;
  const targetEl = isMobile
    ? (document.querySelector('.mobile-compact-stepper') || document.querySelector('.stepper-nav-container'))
    : (document.querySelector('.stepper-nav-container') || document.querySelector('.mobile-compact-stepper'));

  if (!targetEl) return;

  const headerEl = document.querySelector('.site-header');
  const headerHeight = headerEl ? headerEl.offsetHeight : 60;
  const targetY = targetEl.getBoundingClientRect().top + window.pageYOffset - headerHeight - 12;

  window.scrollTo({
    top: Math.max(0, Math.round(targetY)),
    behavior: 'smooth'
  });
}

