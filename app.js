function enableRibbonWheelScroll(el) {
  if (!el) return;
  el.addEventListener('wheel', (e) => {
    if (e.deltaY !== 0 && el.scrollWidth > el.clientWidth) {
      e.preventDefault();
      el.scrollLeft += e.deltaY;
    }
  }, { passive: false });
}

