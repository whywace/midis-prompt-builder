function initAnimatedFavicon() {
  const faviconLink = document.getElementById('dynamic-favicon');
  if (!faviconLink) return;

  const canvas = document.createElement('canvas');
  canvas.width = 64;
  canvas.height = 64;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  function drawSquircle(c, x, y, w, h, r) {
    if (typeof c.roundRect === 'function') {
      c.beginPath();
      c.roundRect(x, y, w, h, r);
    } else {
      c.beginPath();
      c.moveTo(x + r, y);
      c.lineTo(x + w - r, y);
      c.quadraticCurveTo(x + w, y, x + w, y + r);
      c.lineTo(x + w, y + h - r);
      c.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
      c.lineTo(x + r, y + h);
      c.quadraticCurveTo(x, y + h, x, y + h - r);
      c.lineTo(x, y + r);
      c.quadraticCurveTo(x, y, x + r, y);
      c.closePath();
    }
  }

  let step = 0;
  let animTimer = null;

  function drawFrame() {
    step++;
    const t = step * 0.12;

    ctx.clearRect(0, 0, 64, 64);

    // 1. Темный сквиркл-фон (#0E121A)
    drawSquircle(ctx, 2, 2, 60, 60, 15);
    ctx.fillStyle = '#0E121A';
    ctx.fill();

    // 2. Дышащая неоновая оранжевая рамка МИДиС (#FC4C02)
    const pulse = 0.45 + 0.55 * Math.sin(t);
    ctx.lineWidth = 3;
    ctx.strokeStyle = `rgba(252, 76, 2, ${pulse.toFixed(3)})`;
    ctx.stroke();

    // 3. Чёткая буква «М» МИДиС
    ctx.save();
    try {
      if (typeof Path2D !== 'undefined') {
        const mPath = new Path2D('M21 44V20h5.2l5.8 9.2 5.8-9.2H43v24h-4.8V26.8l-5.1 8h-2.2l-5.1-8V44H21Z');
        ctx.fillStyle = '#FFFFFF';
        ctx.fill(mPath);
      } else {
        ctx.fillStyle = '#FFFFFF';
        ctx.beginPath();
        ctx.moveTo(21, 44); ctx.lineTo(21, 20); ctx.lineTo(26.2, 20);
        ctx.lineTo(32, 29.2); ctx.lineTo(37.8, 20); ctx.lineTo(43, 20);
        ctx.lineTo(43, 44); ctx.lineTo(38.2, 44); ctx.lineTo(38.2, 26.8);
        ctx.lineTo(33.1, 34.8); ctx.lineTo(30.9, 34.8); ctx.lineTo(25.8, 26.8);
        ctx.lineTo(25.8, 44); ctx.closePath();
        ctx.fill();
      }
    } catch (e) {
      ctx.fillStyle = '#FFFFFF';
      ctx.font = 'bold 26px sans-serif';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText('M', 32, 33);
    }
    ctx.restore();

    // 4. Пульсирующая AI-искра (четырёхлучевая звезда в правом верхнем углу)
    ctx.save();
    ctx.translate(48, 15);
    const starScale = 0.85 + 0.35 * Math.sin(t * 1.3);
    ctx.scale(starScale, starScale);

    ctx.beginPath();
    ctx.moveTo(0, -6);
    ctx.quadraticCurveTo(0, 0, 6, 0);
    ctx.quadraticCurveTo(0, 0, 0, 6);
    ctx.quadraticCurveTo(0, 0, -6, 0);
    ctx.quadraticCurveTo(0, 0, 0, -6);
    ctx.closePath();
    ctx.fillStyle = '#FC4C02';
    ctx.fill();

    // Белое ядро искры
    ctx.beginPath();
    ctx.arc(0, 0, 1.6, 0, Math.PI * 2);
    ctx.fillStyle = '#FFFFFF';
    ctx.fill();
    ctx.restore();

    try {
      faviconLink.href = canvas.toDataURL('image/png');
    } catch (err) {}
  }

  function startAnimation() {
    if (animTimer) return;
    drawFrame();
    animTimer = setInterval(() => {
      if (!document.hidden) {
        drawFrame();
      }
    }, 120);
  }

  function stopAnimation() {
    if (animTimer) {
      clearInterval(animTimer);
      animTimer = null;
    }
  }

  document.addEventListener('visibilitychange', () => {
    if (document.hidden) {
      stopAnimation();
    } else {
      startAnimation();
    }
  });

  startAnimation();
}

