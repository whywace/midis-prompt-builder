/**
 * Динамически формулирует статус навыков студента, гарантируя отсутствие конфликтов с курсом
 * и отдавая приоритет персональным вводным (если студент начинает с нуля или уже фрилансит).
 * Использует контекстный семантический анализ вместо грубых подстрок для защиты от false positives.
 */
function resolveSkillLevelDescription(course, taskText = '', fearsText = '') {
  const c = parseInt(course, 10) || 1;
  const task = (taskText || '').trim().toLowerCase();
  const fears = (fearsText || '').trim().toLowerCase();
  const combined = (task + ' ' + fears).trim();

  // Вспомогательная функция проверки паттерна с настоящими Unicode word boundaries (корректно для кириллицы)
  const matchWord = (pattern, text) => new RegExp('(?<![\\p{L}\\p{N}])(?:' + pattern + ')(?![\\p{L}\\p{N}])', 'iu').test(text);

  // Фильтр исключений: мечтания, стремления и страхи (не путать с действующим опытом)
  const hasAspirationOnly = matchWord('(?:хочу|планирую|мечтаю|пытаюсь|как\\s+найти)\\s+[а-я\\s]{0,20}(?:заказ[а-я]*|клиент[а-я]*|фриланс[а-я]*)', task) &&
    !matchWord('(?:уже|сейчас|в\\s+данный\\s+момент)\\s+(?:работаю|беру|веду|есть|фрилансю)|опыт\\s+работы|коммерческ[а-я]*\\s+опыт', task);

  const hasNegativeExperienceContext = matchWord('(?:без|нет|никакого|мало|не\\s+хватает|боюсь)\\s+[а-я\\s]{0,20}(?:опыт[а-я]*|клиент[а-я]*|заказ[а-я]*|студи[а-я]*)', combined) &&
    !matchWord('(?:уже|сейчас)\\s+(?:работаю|беру|веду|есть|фрилансю)|опыт\\s+работы\\s+есть|коммерческ[а-я]*\\s+опыт\\s+есть', task);

  // =========================================================================
  // ПРИОРИТЕТ 1 (TIER 1): ДЕЙСТВУЮЩАЯ ПРАКТИКА И КОММЕРЧЕСКИЙ ОПЫТ (ACTIVE PRESENT PRACTICE)
  // Если студент СЕЙЧАС реально берёт заказы или работает — это доминирующий статус над любыми прошлыми упоминаниями новичка!
  // =========================================================================
  const hasWorkExperience = !hasAspirationOnly && !hasNegativeExperienceContext && (
    // Текущие активные действия (беру заказы, сейчас работаю, веду клиентов)
    matchWord('(?:сейчас|уже|в\\s+данный\\s+момент|активно)?\\s*(?:беру|выполняю|делаю|веду)\\s+[а-я\\s]{0,20}(?:заказ[а-я]*|клиент[а-я]*|коммерческ[а-я]*)', task) ||
    matchWord('(?:уже|сейчас|в\\s+данный\\s+момент)\\s+(?:работаю|фрилансю|подрабатываю|тружусь|беру\\s+заказы)', combined) ||
    matchWord('коммерческ[а-я]*\\s+опыт|опыт\\s+коммерческ[а-я]*\\s+(?:разработк[а-я]*|работ[а-я]*|заказ[а-я]*|проект[а-я]*)|опыт\\s+работы\\s+в|коммерческий\\s+опыт\\s+есть', combined) ||
    matchWord('(?:работаю|тружусь|подрабатываю)\\s+в\\s+(?:веб-?|дизайн-?|it-?|креативной\\s+)?студии|в\\s+агентстве|в\\s+компании|на\\s+фрилансе|джуном|junior|дизайнером|разработчиком', combined) ||
    matchWord('(?:практикующий|действующий)\\s+(?:дизайнер|разработчик|специалист|фрилансер)', combined) ||
    matchWord('есть\\s+(?:свои\\s+|реальные\\s+)?(?:клиенты|заказчики|коммерческие\\s+проекты)', task) ||
    // Если студент прямо говорит «не новичок» и подкрепляет это проектами/заказами/опытом
    (matchWord('(?:не|далеко\\s+не|уже\\s+не)\\s+[а-я\\s]{0,30}(?:нович(?:ок|ка|ку|ком|ке|ки)|начинающ[а-я]*)', combined) &&
     matchWord('(?:опыт|проект[а-я]*|заказ[а-я]*|клиент[а-я]*|работ[а-я]*|стек|портфолио)', combined))
  );

  if (hasWorkExperience) {
    return `Практикующий уровень (${c} курс: уже есть опыт прикладных/коммерческих задач, ориентируй на повышение чека, архитектурную глубину и стандарты индустрии)`;
  }

  // =========================================================================
  // ПРИОРИТЕТ 2 (TIER 2): АКТУАЛЬНОЕ ИЗУЧЕНИЕ С НУЛЯ (CURRENT BEGINNER / SCRATCH)
  // Проверяется только если нет подтверждённой действующей коммерческой практики.
  // Исключаем:
  // 1. Процедурные страхи защиты диплома/выступлений («первый раз защищаю диплом перед ГЭК»)
  // 2. Отрицания статуса новичка («я не новичок», «не сказал бы что я новичок», «далеко не новичок»)
  // 3. Прошедшее время и временной контраст («раньше был новичком», «был с нуля»)
  // =========================================================================
  const isDefenseOrSpeechFirstTime = /(?:первый\s+раз|впервые)\s+[а-я\s]{0,25}(?:защищ|выступа|перед|на\s+публик|презентац|комисси|гэк|диплом|собеседован)/iu.test(combined);
  const isNegatedBeginner = matchWord('(?:не|далеко\\s+не|уже\\s+не|совсем\\s+не|точно\\s+не|вовсе\\s+не)\\s+[а-я\\s]{0,30}(?:нович(?:ок|ка|ку|ком|ке|ки)|с\\s+нуля|начинающ[а-я]*|чайник[а-я]*)', combined);
  const isPastTenseBeginner = matchWord('(?:раньше|когда-то|ранее|был|была|были)\\s+[а-я\\s]{0,30}(?:новичк[а-я]*|с\\s+нуля|ничего\\s+не\\s+умел[а-я]*)', combined);

  const isScratchOrBeginner = !isDefenseOrSpeechFirstTime && !isNegatedBeginner && !isPastTenseBeginner && (
    matchWord('с\\s+нуля|с\\s+самых\\s+азов|полный\\s+ноль|совсем\\s+ноль', combined) ||
    matchWord('(?:нет|без)\\s+(?:базы|основы|знаний|понимания\\s+софта)', combined) ||
    matchWord('(?:не\\s+знаю|не\\s+владею|не\\s+умею\\s+работать\\s+в)\\s+(?:софт[а-я]*|программ[а-я]*|figma|blender|photoshop|код[а-я]*|стек[а-я]*)', combined) ||
    matchWord('только\\s+начинаю(?:\\s+(?:осваивать|изучать|погружаться|разбираться|учить))?', combined) ||
    matchWord('(?:первый\\s+раз|впервые)\\s+(?:открыл|вижу|сел\\s+за|изучаю|пробую|в\\s+этой\\s+теме|в\\s+программе|в\\s+софте)', combined) ||
    matchWord('(?<!(?:не|далеко\\s+не|уже\\s+не|совсем\\s+не|точно\\s+не|вовсе\\s+не|был|была|раньше)\\s+(?:совсем\\s+|вообще\\s+|полным\\s+)?)нович(?:ок|ка|ку|ком|ке|ки)', combined)
  );

  if (isScratchOrBeginner) {
    if (c >= 3) {
      return `Начальный в этой теме (осваиваю профильный стек с нуля в сжатые сроки ${c} курса: нужны понятные пошаговые алгоритмы, без заумной терминологии)`;
    }
    return `Начальный уровень (освоение с нуля: погружение в базовые понятия, терминологию и интерфейс инструментов)`;
  }

  // =========================================================================
  // ПРИОРИТЕТ 3 (TIER 3): БАЗОВЫЕ АДАПТИВНЫЕ СТАТУСЫ ПО КУРСУ
  // =========================================================================
  switch (c) {
    case 1:
      return '1 курс (погружение в основы специальности, изучение базы, терминологии и ключевого софта)';
    case 2:
      return '2 курс (углубление в профильные предметы, первые курсовые работы и прикладные учебные проекты)';
    case 3:
      return '3 курс (старший курс: прикладные кейсы, самостоятельное владение стеком, подготовка к практике и стажировкам)';
    case 4:
      return '4 курс (выпускной этап: преддипломная практика, подготовка ВКР/диплома, готовность к работе в индустрии)';
    default:
      return `${c} курс (освоение программы и прикладных компетенций направления)`;
  }
}

